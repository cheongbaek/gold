    def cb_fix(self, msg: NavSatFix):
        if math.isnan(msg.latitude) or math.isnan(msg.longitude):
            return
        if self.lat0 is None:
            self.lat0, self.lon0 = msg.latitude, msg.longitude
        self.x, self.y = latlon_to_xy(msg.latitude, msg.longitude,
                                      self.lat0, self.lon0)
        self.fix_ok = (not self.require_rtk) or (msg.status.status >= RTK_FIXED_STATUS)
        self.fix_time = time.time()

        self._update_gps_speed(self.fix_time)

        if self.state in (S_MAP_HEADING, S_DRIVE_HEADING) and self.fix_ok:
            self.head_est.add(self.x, self.y)
        self._fuse_gps_course()

    def _update_gps_speed(self, now):
        """5Hz fix 변위로 속도를 만든다. ★상수 GPS_SPEED_* 절에 근거가 있다★

        ★fix_ok(RTK Fixed)를 따지지 않는다★ 이 값은 '얼마나 빠른가'만 답하면 되고,
        Float 로 떨어져도 변위의 크기는 여전히 쓸 만하다. 반대로 Fixed 를 요구하면
        RTK 가 흔들리는 순간 종점 감속이 임계를 못 넘어 굳는다 — 그쪽이 더 위험하다.
        """
        self._gps_trail.append((now, self.x, self.y))
        if len(self._gps_trail) > GPS_SPEED_WIN:
            del self._gps_trail[0]
        if len(self._gps_trail) < 2:
            return
        t0, x0, y0 = self._gps_trail[0]
        t1, x1, y1 = self._gps_trail[-1]
        dt = t1 - t0
        if dt <= 0.0 or dt > GPS_SPEED_MAX_DT:
            # 두절 뒤 첫 표본 — 낡은 점과 이어 붙이면 엉뚱한 속도가 나온다
            self._gps_trail = [self._gps_trail[-1]]
            return
        self._gps_kmh = 3.6 * math.hypot(x1 - x0, y1 - y0) / dt
        self._gps_kmh_t = now

    def cb_imu(self, msg: Imu):
        now = time.time()
        if self.imu_time > 0.0 and self.heading is not None:
            dt = now - self.imu_time
            if 0.0 < dt < 0.5:
                # 자이로 z(CCW +)를 그대로 적분한다. 절대 기준은 초기화가 잡아준다.
                self.heading = wrap180(self.heading + math.degrees(self.gyro_z) * dt)
        self.gyro_z = float(msg.angular_velocity.z)
        self.imu_time = now

    def cb_encoder(self, msg: Int32):
        """★중앙값 3점 필터★ A보드 기동 블랭킹 구간의 허수 카운트를 죽인다 —
        상단 ENC_MEDIAN_N 주석 참고(정상 4~5 인데 34 까지 튄 실측이 있다)."""
        self._enc_buf.append(float(msg.data))
        if len(self._enc_buf) > ENC_MEDIAN_N:
            del self._enc_buf[0]
        med = sorted(self._enc_buf)[len(self._enc_buf) // 2]
        self.enc_pulse = med * ENC_SUM_TO_PULSE

    def cb_speed(self, msg: Float32):
        """speed.py 의 IMU 적분 속도 [km/h]. ★저속 펄스 보정에만 쓴다★
        (추종 기하·상태 판정에는 절대 쓰지 않는다 — speed.py 헤더의 정확도 실측 참고:
        절대속도는 26초 창에서 2배 수준으로 틀린다. 정지/기동 판정만 정확하다)."""
        self.speed_kmh = float(msg.data)
        self.speed_time = time.time()

    def cb_mode(self, msg: Bool):
        new = bool(msg.data)
        if self.auto_mode is None:
            self.auto_mode = new            # 첫 수신은 엣지로 치지 않는다
            self.event(f"주행모드 최초 인식: {'자율' if new else '수동조종'}")
            return
        if new == self.auto_mode:
            return
        self.auto_mode = new
        self.on_mode_edge(rising=new)

    def cb_estop(self, msg: Bool):
        """E-STOP(D12) 엣지. ★[2026-08-14] E-STOP 은 더 이상 상태를 소유하지 않는다★

        예전에는 S_ESTOP 이라는 상태로 빠져 ★매핑까지 포함해 전부★ 막았고, 해제될
        때 IDLE 로 돌아왔다. 지금은 둘로 갈랐다:
          · 진행 중이던 ★자율주행만★ 취소하고 메뉴(IDLE)로 돌려보낸다.
          · 그 뒤로는 '자율주행 진입 금지' ★플래그★ 로만 남는다(self.estop) —
            게이트는 cb_drive_cmd 의 DRIVE_START 한 곳뿐이다.

        ★매핑은 E-STOP 중에도 걸 수 있다★ 매핑은 사람이 페달로 모는 절차이고,
        E-STOP 이 물린 동안에는 A보드가 구동을 끊어 차가 애초에 구르지 않는다 —
        점이 쌓이지 않으므로 경로가 오염되지 않는다. 준비(스위치·화면·경로 이름)를
        미리 해 두고 해제되는 순간 바로 출발할 수 있는 쪽이 실차에서 낫다.

        ★소프트웨어로 E-STOP 을 빠져나가는 구멍은 여전히 없다★ 예전 가드가 막던
        것은 'E-STOP 상태에서 STOP 명령으로 IDLE 로 나가는 것'이었는데, 이제 그
        상태 자체가 없고 금지 조건은 /estop 하드웨어 신호를 그대로 읽는 플래그다.
        어떤 키 입력도 이 플래그를 못 바꾼다.
        """
        new = bool(msg.data)
        if new == self.estop:
            return
        self.estop = new
        if new:
            if self.state in (S_DRIVE_HEADING, S_DRIVE_RUN, S_DRIVE_DONE):
                self.enter(S_IDLE, "🚨 E-STOP — 자율주행 취소, 메뉴로 복귀")
            else:
                self.event("🚨 E-STOP — 자율주행 진입 금지(매핑은 가능)")
        else:
            self.event("✅ E-STOP 해제 — 자율주행 가능")

    def cb_drive_cmd(self, msg: String):
        """prompt 하달. 'STOP' = 즉시 정지+리니어 2단 / 'MAP_START'·'DRIVE_START' =
        스위치가 이미 목표 위치일 때 엣지 없이 직접 시작 / 그 외 = 경로 선택.

        ★[2026-08-14] E-STOP 게이트는 DRIVE_START 한 곳뿐이다★ 예전에는 이 함수
        전체가 E-STOP 중에 아무것도 받지 않았는데, 그러면 매핑 시작도 함께 막힌다.
        지금은 매핑·경로선택·STOP 은 그대로 받고 ★자율주행 진입만★ 거절한다
        (cb_estop 주석 참고). 화면(prompt)도 같은 조건으로 메뉴를 막지만,
        ★진짜 게이트는 여기다★ — 화면은 갈아 끼울 수 있고 이 노드는 하나다.
        """
        cmd = str(msg.data).strip()
        if not cmd:
            return
        upper = cmd.upper()
        if upper == 'STOP':
            if self.state in (S_DRIVE_HEADING, S_DRIVE_RUN):
                self.enter(S_DRIVE_DONE, "🛑 정지 명령 — 리니어 2단 체결")
            else:
                self.enter(S_IDLE, "🛑 정지 명령")
            return
        if upper == 'MAP_START':
            # ★스위치가 이미 수동조종이라 엣지가 없다★ prompt 가 대신 눌러 준다 —
            #   IDLE·수동조종일 때만 받아준다(엣지가 만드는 전이와 동일하게).
            if self.state != S_IDLE:
                self.event(f"⚠️ 매핑 시작 실패 — 현재 상태 {self.state}(IDLE 에서만 가능)")
            elif self.auto_mode is not False:
                self.event("⚠️ 매핑 시작 실패 — 스위치가 수동조종이어야 한다")
            else:
                self.enter(S_MAP_HEADING, "🗺️ 매핑 시작(prompt) — 페달로 곧게 굴려 헤딩을 잡을 것")
            return
        if upper == 'DRIVE_START':
            # ★스위치가 이미 자율주행이라 엣지가 없다★ 위와 대칭.
            if self.estop:
                # ★E-STOP 중 자율주행 진입 금지 [2026-08-14]★ 물려 있는 동안은
                #   A보드가 구동을 끊으므로 헤딩 초기화부터 성립하지 않고, 해제
                #   순간에 차가 갑자기 굴러 나가는 것이 제일 위험하다.
                self.event("🚨 주행 시작 실패 — E-STOP 체결 중이다(해제 후 다시)")
            elif self.state != S_IDLE:
                self.event(f"⚠️ 주행 시작 실패 — 현재 상태 {self.state}(IDLE 에서만 가능)")
            elif self.auto_mode is not True:
                self.event("⚠️ 주행 시작 실패 — 스위치가 자율주행이어야 한다")
            elif not getattr(self, 'raw_wps', None):
                self.event("⚠️ 주행 시작 실패 — 경로가 선택되지 않았다")
            else:
                self.enter(S_DRIVE_HEADING, f"▶ 주행 시작(prompt) [{self.route_name}]")
            return
        self.select_route(cmd)

