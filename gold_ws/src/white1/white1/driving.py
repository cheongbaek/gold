        out = max(int(self.brake_now), int(self.tl_brake_req()))
        now = time.time()
        if not force and out == self._brake_out:
            if out <= 0 or (now - self._brake_t) < BRAKE_KEEPALIVE_S:
                return
        self._brake_out = out
        self._brake_t = now
        self.pub_brake.publish(Int32(data=out))

