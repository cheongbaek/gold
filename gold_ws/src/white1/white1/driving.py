    def low_speed_trim(self, ref):
        """저속에서 실제 속도를 보고 REF 를 ±REF_TRIM_MAX_PULSE 만큼 밀어 준다.
        [2026-08-12 신설 — 상단 '저속 펄스 보정' 절에 근거와 예시가 있다]

            out = REF + clamp(REF − 실측펄스, −2, +2)      0 ≤ out ≤ 15

        ★동작 조건이 좁다★ 자율주행 추종 중(DRIVE_RUN)이고 1 ≤ REF ≤ 3 일 때만이다.
          · REF 0 에서는 절대 걸지 않는다 — 세우려는 지시를 보정이 뒤집으면 안 된다.
          · REF 4 이상은 이미 지령대로 구르는 구간이고, 거기서 보정하면
            MAX_PULSE_LIMIT 를 우회하는 과속 경로가 된다.
          · DRIVE_HEADING 은 '곧게 굴러 헤딩을 잡는' 구간이라 속도를 흔들면 안 된다.
        """
        now = time.time()
        # ★종점 크립의 킥은 보정을 태우지 않는다 [2026-08-12]★ 킥은 '정지 상태를
        #   떼어내는 힘'을 정해 놓고 넣는 것이라, 실측 0 을 본 보정이 그 위에 또 얹히면
        #   종점 2m 앞에서 낼 속도가 아니게 된다(ref 4 + 실측 0 → out 6).
        # ★코너 1단 제동 중에도 태우지 않는다 [2026-08-18]★ ★같은 함정이고 더 나쁘다★
        #   제동 중에는 arduino 가 A보드 REF 를 0 으로 덮으므로(compose (4)) 차가
        #   실제로 줄어든다 → 보정은 'REF 2 인데 실측 0' 을 보고 +2 를 얹어 out 4 를
        #   낸다. 그 4 는 제동이 풀리는 순간 그대로 나가서 ★제동해서 줄인 속도를 그
        #   자리에서 되돌린다★ — 감속의 목적을 정확히 무효화한다.
        if self.state != S_DRIVE_RUN or not (1 <= ref <= REF_TRIM_REF_MAX) \
                or now < self._goal_kick_until \
                or self._cb_state == CB_BRAKING:
            self._trim = 0
            self._trim_ref = ref
            return ref

        # REF 가 바뀌면 즉시 다시 판단하고, 아니면 HOLD 주기로만 다시 판단한다
        # (20Hz 로 매 틱 계산하면 속도가 따라오기 전에 보정이 널뛴다).
        if ref != self._trim_ref or now - self._trim_t >= REF_TRIM_HOLD_S:
            meas = self.measured_pulse()
            self._diag_meas = meas
            if meas is not None:
                err = ref - meas
                self._trim = max(-REF_TRIM_MAX_PULSE,
                                 min(REF_TRIM_MAX_PULSE, int(round(err))))
            else:
                self._trim = 0
            self._trim_t = now
            self._trim_ref = ref

        return max(0, min(REF_TRIM_OUT_MAX, ref + self._trim))

    def cb_tl_brake_req(self, msg: Int32):
        """신호등 노드가 요구하는 브레이크 단계. ★내 값과 max 로 합쳐서 낸다★

        합치는 이유는 master 와 같다 — /brake_level 은 마지막 발행자가 이기는 명령
        토픽이라, 두 발행자가 다른 값을 내면 리니어가 그 주기로 왕복한다. 같은 값을
        내면 다툼 자체가 없어진다.
        """
        lvl = max(0, min(BRAKE_FULL, int(msg.data)))
        self._tl_req = lvl
        self._tl_req_t = time.time()
        if lvl > 0:
            self._tl_hold_level = lvl        # 해제 유예의 기준
            self._tl_hold_t = self._tl_req_t

    def tl_brake_req(self):
        """신호등이 지금 요구하는 단계. ★해제는 TL_REQ_RELEASE_HOLD_S 유예★

        무는 것은 즉시, 놓는 것은 마지막 '0 아닌 요구' 로부터 1초 뒤다. 인지가 한 번
        흔들리거나 토픽이 잠깐 밀려도 리니어가 왕복하지 않게 하려는 것이고, 신호등
        노드 자체에도 같은 유예가 있다(그쪽 red_release_hold_s) — ★두 겹으로 막는다★.
        요구가 아예 끊기면(노드 사망) 유예가 지난 뒤 0 이 되어 풀린다.
        """
        now = time.time()
        if (now - self._tl_hold_t) <= TL_REQ_RELEASE_HOLD_S:
            return self._tl_hold_level
        if (now - self._tl_req_t) > TL_REQ_STALE_S:
            return 0
        return self._tl_req

